def shap_by_cat(recs, c):
    return np.array([mean_abs(r) for r in recs if cat(r) == c])

def mw(a, b, label):
    a = np.asarray(a, dtype=float); b = np.asarray(b, dtype=float)
    if len(a) < 2 or len(b) < 2:
        return {"test": label, "n1": len(a), "n2": len(b), "U": float("nan"),
                "p": float("nan"), "|r|": float("nan")}
    res = mannwhitneyu(a, b, alternative="two-sided")
    U = float(res.statistic); p = float(res.pvalue)
    r = abs(1.0 - 2.0 * U / (len(a) * len(b)))
    return {"test": label, "n1": len(a), "n2": len(b), "U": U, "p": p, "|r|": r}

