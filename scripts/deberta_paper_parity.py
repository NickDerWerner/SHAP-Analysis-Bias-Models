def overlap(a, b, label_a, label_b):
    inter = len(a & b)
    union = len(a | b)
    p_a = len(a) / n_neg
    p_b = len(b) / n_neg
    expected_under_indep = p_a * p_b * n_neg
    return {
        "pair": f"{label_a} ∩ {label_b}",
        f"|{label_a}|": len(a),
        f"|{label_b}|": len(b),
        "observed_∩": inter,
        "expected_indep": round(expected_under_indep, 2),
        "ratio_obs/exp": round(inter / expected_under_indep, 2) if expected_under_indep else float("nan"),
        "Jaccard": round(inter / union, 4) if union else float("nan"),
    }

