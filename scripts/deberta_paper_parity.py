def load_jsonl(p):
    return [json.loads(l) for l in open(p, "r", encoding="utf-8")]


def mean_abs(rec):
    wa = rec["word_attribs"]
    return float(np.mean([abs(x["shap"]) for x in wa])) if wa else 0.0


def max_abs(rec):
    wa = rec["word_attribs"]
    return float(np.max([abs(x["shap"]) for x in wa])) if wa else 0.0


def sum_abs(rec):
    wa = rec["word_attribs"]
    return float(np.sum([abs(x["shap"]) for x in wa])) if wa else 0.0


def cat(rec):
    g, p = int(rec["gold"]), int(rec["pred"])
    if g == 1 and p == 1: return "TP"
    if g == 0 and p == 1: return "FP"
    if g == 0 and p == 0: return "TN"
    return "FN"


